import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { root, write, readJson } from './lib/site.mjs';

const normalize = value => value.replaceAll('\\', '/');
async function walk(dir) {
  const entries = await fs.readdir(path.join(root, dir), { withFileTypes: true });
  return (await Promise.all(entries.filter(e => !['.git', 'node_modules', 'dist', '.playwright-browsers',
    'test-results', 'tests/screens', '.npm-cache', 'playwright-report'].includes(e.name))
    .map(e => e.isDirectory() ? walk(dir + '/' + e.name) : dir + '/' + e.name))).flat();
}
const files = (await walk('design-export')).sort();
const records = [];
for (const file of files) {
  const bytes = await fs.readFile(path.join(root, file));
  const ext = path.extname(file).toLowerCase();
  const record = { path: file, extension: ext, bytes: bytes.length,
    sha256: createHash('sha256').update(bytes).digest('hex') };
  if (['.md', '.mdx', '.html', '.css', '.js', '.json', '.yaml', '.yml', '.svg', '.txt'].includes(ext)) {
    const text = bytes.toString('utf8');
    record.lines = text.split(/\r?\n/).length;
    record.headings = [...text.matchAll(/^#{1,6}\s+(.+)$/gm)].map(m => m[1]);
    if (ext === '.json') {
      try { record.jsonKeys = Object.keys(JSON.parse(text)); }
      catch (error) { record.parseError = error.message; }
    }
    if (ext === '.html') {
      record.title = text.match(/<title[^>]*>([^<]*)/i)?.[1] ?? null;
      record.viewport = text.match(/<meta[^>]*name=["']viewport["'][^>]*>/i)?.[0] ?? null;
      record.references = [...text.matchAll(/(?:src|href)=["']([^"']+)["']/g)].map(m => m[1]);
      record.textSample = text.replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, '')
        .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '').replace(/<[^>]+>/g, ' ')
        .replace(/\s+/g, ' ').trim().slice(0, 300);
    }
    if (ext === '.svg') record.viewBox = text.match(/viewBox=["']([^"']+)/)?.[1] ?? null;
  }
  records.push(record);
}
const hashes = new Map();
for (const record of records) hashes.set(record.sha256, [...(hashes.get(record.sha256) ?? []), record.path]);
const duplicates = [...hashes.values()].filter(group => group.length > 1);
const counts = {};
for (const record of records) counts[record.extension] = (counts[record.extension] ?? 0) + 1;
const manifest = await readJson(path.join(root, 'design-export/MANIFEST.json'));
const registry = await readJson(path.join(root, 'src/page-registry.json'));
const tokens = await readJson(path.join(root, 'design-export/design-system-v2/tokens/tokens.json'));
const screenshotPaths = page => (page.screenshots ?? []).map(item => typeof item === 'string' ? item : item.path);
const mapped = manifest.pages.map(page => ({ ...page,
  runtime: registry.pages.find(item => item.id === page.id) ?? null,
  missingEvidence: [...(page.sourceHtml ?? []), ...screenshotPaths(page)].filter(file => !files.includes(file))
}));
const output = path.join(root, 'docs/ai');
await write(path.join(output, 'design-audit.json'), JSON.stringify({ schemaVersion: 1,
  scope: 'Structural/content extraction; visual review is separate. No source files are modified.',
  counts, duplicates, records, pages: mapped }, null, 2) + '\n');
const link = file => `[${file}](<../../${normalize(file)}>)`;
const inventory = ['# Design export inventory', '',
  'Generated by `node tools/audit-design.mjs`. All export files are read; JSON is parsed, HTML titles, text samples, asset references and viewport declarations are extracted, SVG viewBoxes and SHA-256 duplicates are recorded.', '',
  'File-level records and page/state candidate mappings: [design-audit.json](design-audit.json). This is structural evidence, not a claim that every artboard was visually reviewed.', '',
  `Files: ${files.length}. Byte-identical duplicate groups: ${duplicates.length}.`, '',
  ...Object.entries(counts).map(([ext, count]) => `- ${ext || '(no extension)'}: ${count}`), '',
  '## Families', '',
  '- batches/: eight original batches; HTML artboards, image references, historical CSS and canvas JSON.',
  '- design-system-v2/components/: component README and preview HTML; source state/interaction/copy specifications.',
  '- design-system-v2/tokens/: canonical JSON and exported CSS. Production CSS is generated by tools/lib/design-system.mjs.',
  '- design-system-v2/assets/: local SVG icons, logos, service/customer/salon photos; fonts/ includes archived widths.',
  '- design-system-v2/archive/: historical proposals, never active implementation authority.', '',
  '## Token coverage', '', ...Object.keys(tokens).filter(k => !['name', 'version'].includes(k))
    .map(k => `- ${k}: ${tokens[k].tokens?.length ?? tokens[k].groups?.length ?? 0} tokens/style groups.`), '',
  'No dedicated breakpoint, container or z-index family exists in tokens.json. Use the existing contract and approved page briefs; do not invent token values. Normal-width Yekan Bakh 300/400/600 overrides the wider font archive.', '',
  '## Gaps', '', ...mapped.filter(p => p.mappingStatus !== 'mapped' || p.missingEvidence.length)
    .map(p => `- ${p.id}: ${p.mappingStatus}; missing referenced files: ${p.missingEvidence.length}.`), '',
  'A null screenshot or selector is unverified evidence. Render the exact HTML using the existing screenshot helper after checking its handoff. Duplicate hashes do not authorize deleting original evidence.', ''];
await write(path.join(output, 'DESIGN_EXPORT_INVENTORY.md'), inventory.join('\n'));
const sourceMap = ['# Design source map', '',
  'Generated from the immutable manifest and current registry. Each page section lists all candidates, not an invented canonical state selection. Read the matching handoff before choosing a variant.', '',
  'Common tokens: ' + link('design-export/design-system-v2/tokens/tokens.json') + '. Component sources and ownership: [COMPONENT_CATALOG.md](COMPONENT_CATALOG.md).', '',
  'Common rules: [implementation](DESIGN_IMPLEMENTATION_CONTRACT.md), [responsive](RESPONSIVE_DESIGN_CONTRACT.md), [motion](MOTION_SPEC.md), [accessibility and QA](QA_CHECKLIST.md). Copy/assets come from the selected exact state HTML and its handoff, never the filename alone.', ''];
for (const page of mapped) sourceMap.push(`## ${page.id}`, '',
  `Route/context: ${page.routeTemplate ?? 'embedded/no independent route'}. Preview: ${page.previewPath ?? 'none'}. Mapping: ${page.mappingStatus}.`,
  `Implementation: ${page.runtime?.implementationStatus ?? 'unassigned'}. Template: ${page.runtime?.template ? link('src/Views/' + page.runtime.template) : 'none (placeholder)'}.`,
  `Default mobile candidate: ${page.preferredSourceHtml ? link(page.preferredSourceHtml) : 'not uniquely selected'}. Reference capture: 390×844; verify the source canvas dimensions before pixel comparison.`,
  'Desktop: see approved briefs in docs-work/desktop-layouts; absence is not approval. No desktop reference is inferred from filenames.',
  `Runtime states: ${(page.runtime?.variants ?? []).map(v => v.query).join(', ') || 'default / consult handoff'}.`,
  `Fixture: ${page.runtime?.mockData ? link('src/' + page.runtime.mockData) : 'none; later phase owns content'}.`,
  '', 'Source HTML candidates:', '', ...(page.sourceHtml ?? []).map(file => '- ' + link(file)), '',
  'Named screenshots: ' + (screenshotPaths(page).map(link).join(', ') || 'none verified; render exact HTML'), '',
  'Per-state component, copy, asset, viewport, responsive and motion selections must be completed in the [page spec](templates/page-spec.md) for the assigned page; unresolved sources remain gaps.', '');
await write(path.join(output, 'DESIGN_SOURCE_MAP.md'), sourceMap.join('\n'));
console.log(`Audited ${files.length} exports, ${mapped.length} contexts, ${duplicates.length} duplicate groups.`);
